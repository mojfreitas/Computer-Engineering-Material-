PRINT_FICHEIRO PROC
    XOR AL, AL
    CALL OPEN_FILE
    JC ERRO_ABRIR
    MOV HANDLE_FICH, AX
    JMP LER_CICLO

ERRO_ABRIR:
    LEA DX, ERRO_OPEN
    CALL PRINT_STRING
    JMP SAI_F

LER_CICLO:
    MOV BX, HANDLE_FICH
    MOV CX, 1
    LEA DX, CAR_FICH
    CALL READ_FILE
	JC ERRO_LER
	CMP AX, 0		;EOF?
	JE FECHA_FICHEIRO
	MOV DL, CAR_FICH
	CALL PRINT_CHAR
	JMP	LER_CICLO

ERRO_LER:
    LEA DX, ERRO_LER_MSG
    CALL PRINT_STRING

FECHA_FICHEIRO:
    MOV BX, HANDLE_FICH
    CALL CLOSE_FILE
    JNC SAI_F
    LEA DX, ERRO_CLOSE
    CALL PRINT_STRING

SAI_F:	
	RET
PRINT_FICHEIRO ENDP		




