VERIFICA_VENCEDOR_9X9 ENDP




PREENCHE_BOARD PROC
	XOR BX, BX
	MOV CX, 3
	
PREENCHE_BOARD_LOOP:
	CMP BX, 3
	JE PREENCHE_BOARD_SAIR
	GOTO_XY IDX_CURR_X, IDX_CURR_Y
	MOV DL, JOGADOR_CURR_CHAR
	CALL PRINT_CHAR
	ADD IDX_CURR_X, 3
	LOOP PREENCHE_BOARD_LOOP
	MOV CX, 3
	INC BX
	INC IDX_CURR_Y
	SUB IDX_CURR_X, 9
	JMP PREENCHE_BOARD_LOOP

PREENCHE_BOARD_SAIR:
	RET
PREENCHE_BOARD ENDP




