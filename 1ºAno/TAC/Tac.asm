MAP9X9 PROC
	MOV AL, JOGADOR_CURR_CHAR
	CMP DH, 7							;Procura a LINHA_9X9 onde o char foi
	JE L1_9X9							;introduzido e adiciona o offset
	CMP DH, 8							;necessario
	JE L2_9X9							;Fica mapeado na array por linhas,
	CMP DH, 9							;o que pode nao ser a opcao mais
	JE L3_9X9							;pratica para calculos, mas simplifica
	CMP DH, 11							;o mapeamento
	JE L4_9X9
	CMP DH, 12
	JE L5_9X9
	CMP DH, 13
	JE L6_9X9
	CMP DH, 15
	JE L7_9X9
	CMP DH, 16
	JE L8_9X9
	CMP DH, 17
	JE L9_9X9

L1_9X9:
	MOV BH, 7
