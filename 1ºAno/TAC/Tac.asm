SELECIONA_PRIMEIRO_JOGADOR PROC
	MOV BYTE PTR [JOGADOR_CURR_CHAR], 'X'    ;Define o jogador atual como 'X'      
	CALL READ_SYSTEM_TIMER								
	MOV AL, DL						    ;Move parte do tempo atual para AL
	AND AL, 1						    ;Vai dar ou 1 ou 0
	CMP AL, 0								
	JE JOGADOR_X						;Caso o resultado for 0
	JMP JOGADOR_O						;Caso o resultado for 1

JOGADOR_X:
	MOV BYTE PTR [JOGADOR1_CHAR], 'X'	;Define o jogador 1 como X
	MOV BYTE PTR [JOGADOR2_CHAR], 'O'	;Define o jogador 2 como O
	RET

JOGADOR_O:
	MOV BYTE PTR [JOGADOR1_CHAR], 'O'	;Define o jogador 1 como O
	MOV BYTE PTR [JOGADOR2_CHAR], 'X'	;Define o jogador 2 como X
	RET
SELECIONA_PRIMEIRO_JOGADOR ENDP




INICIALIZA_JOGO PROC
	LEA DI, BOARD_3X3
	LEA SI, BOARD_9X9
	LEA BX, JOGADOR1_NOME + 2
	MOV CX, 81
	MOV AL, 'L'

INICIALIZA_BOARD_LOOP:
	MOV [SI], AL
	INC SI
	LOOP INICIALIZA_BOARD_LOOP
	MOV CX, 9
	
INICIALIZA_BOARD_LOOP1:
	MOV [DI], AL
	INC DI
	LOOP INICIALIZA_BOARD_LOOP1
	MOV CX, 18
	MOV AL, '$'
	
INICIALIZA_JOGADOR1:
	MOV [BX], AL
	LOOP INICIALIZA_JOGADOR1
	LEA BX, JOGADOR2_NOME + 2
	MOV CX, 18
	
INICIALIZA_JOGADOR2:
	MOV [BX], AL
	LOOP INICIALIZA_JOGADOR2
	RET
INICIALIZA_JOGO ENDP




MOVER PROC										
	MOV AX, 0B800H						;Mete o ES a apontar para a 			
	MOV	ES, AX							;memoria de video
	MOV POS_X, 38						
	MOV POS_y, 12
	LEA SI, BOARD_9X9						;Carrega o endereço da BOARD_9X9 para SI
	
MOVER_CICLO:
	GOTO_XY	POS_X, POS_Y				;Vai para nova posição
	CALL READ_CHAR_CURSOR_POS
	MOV CHAR, AL						;Carrega CHAR com char na pos do cursor
	
LER_SETA:	
	CALL LE_TECLA						
	CMP	AH, 1
	JE CIMA								;Caso tecla pressionada salta para CIMA
	CMP AL, JOGADOR_CURR_CHAR
	JNE LER_SETA
	GOTO_XY	POS_X, POS_Y 				;Verifica se pode escrever char no ecra
	MOV	CL, CHAR						
	CMP	CL, 32							
	JNE LER_SETA						;So escreve se for espaço em branco
	CALL GET_CURSOR_POS
	CALL MAP9X9
	MOV	DL, AL							;Carrega DL com char
	CALL PRINT_CHAR
	JMP MOVER_FIM
	
CIMA:		
	CMP AL, 48H							;Se a tecla nao for seta para cima
	JNE	BAIXO							;Salta para BAIXO
	CMP DH, 7							;Se estiver em Y = 7, nao deixa subir
	JE LER_SETA
	DEC	POS_Y							;Sobe uma posicao
	JMP	MOVER_CICLO

BAIXO:
	CMP	AL, 50H							;Se a tecla nao for seta para baixo
	JNE	ESQUERDA                        ;Salta para ESQUERDA
	CMP DH, 17                          ;Se estiver em X = 17, nao deixa descer
	JE LER_SETA                         
	INC POS_Y			                ;Desce uma posicao
	JMP	MOVER_CICLO

ESQUERDA:
	CMP	AL, 4BH							;Se a tecla nao for seta para esquerda
	JNE	DIREITA                         ;Salta para DIREITA
	CMP DL, 26                          ;Se estiver em X = 26, nao deixa andar
	JE LER_SETA                         ;para a esquerda
	SUB POS_X, 3                        ;Anda 3 posicoes para a esquerda
	JMP	MOVER_CICLO

DIREITA:
	CMP	AL, 4DH							;Se a tecla nao for seta para direita
	JNE	LER_SETA                        ;Salta para LER_SETA
	CMP DL, 50                          ;Se estiver em X = 50, nao deixa andar
	JE LER_SETA                         ;para a direita
	ADD POS_X, 3                        ;Anda 3 posicoes para a direita
	JMP	MOVER_CICLO

MOVER_FIM:		
	RET
MOVER ENDP




MOVER_MENU PROC

CICLO_MENU:		
	GOTO_XY	POS_X,POS_Y					;Vai para nova posição
	
LER_SETA:	
	CALL LE_TECLA
	CMP	AH, 1
	JE CIMA_MENU
	CALL GET_CURSOR_POS	
	RET
	
CIMA_MENU:								
	CMP AL, 48H							;Se a tecla nao for seta para cima
	JNE	BAIXO_MENU                      ;Salta para BAIXO_MENU
	CMP DH, 18                          ;Se estiver em Y = 18, nao deixa subir
	JE CICLO_MENU                       
	DEC	POS_Y				            ;Sobe duas posicoes
	DEC POS_Y
	JMP	CICLO_MENU

BAIXO_MENU:		
	CMP	AL, 50H							;Se a tecla nao for seta para baixo
	JNE	CICLO_MENU                      ;Salta para CICLO_MENU
	CMP DH, 22                          ;Se estiver em Y = 22, nao deixa descer
	JE CICLO_MENU                       
	INC POS_Y		                    ;Desce duas posicoes
	INC POS_Y
	JMP	CICLO_MENU
MOVER_MENU ENDP




ATUALIZA_JOGADOR PROC
	MOV AL, JOGADOR_CURR_CHAR
	CMP AL, JOGADOR1_CHAR
	JNE ATUALIZA_JOGADOR2
	GOTO_XY 64, 3
	MOV DL, ' '
	CALL PRINT_CHAR
	GOTO_XY 64, 2
	MOV DL, '>'
	CALL PRINT_CHAR
	RET
	
ATUALIZA_JOGADOR2:
	GOTO_XY 64, 2
	MOV DL, ' '
	CALL PRINT_CHAR
	GOTO_XY 64, 3
	MOV DL, '>'
	CALL PRINT_CHAR
	RET
ATUALIZA_JOGADOR ENDP




MUDA_JOGADOR PROC
	CMP JOGADOR_CURR_CHAR, 'X'
	JE MUDA								;Se o char jogado era X, troca para O
	MOV JOGADOR_CURR_CHAR, 'X'				;Senao, passa a ser X
	JMP VOLTA
	
MUDA:
	MOV JOGADOR_CURR_CHAR, 'O'
	JMP VOLTA
	
VOLTA:
	RET
MUDA_JOGADOR ENDP




VERIFICA_VENCEDOR_3X3 PROC
	XOR BX, BX
	XOR CX, CX
	XOR DX, DX
	LEA DI, BOARD_3X3
	
VERIFICA_LINHA3X3:
	CMP CX, 3
	JE VERIFICA_COLUNA3X3
	CMP DX, 3
	JE GANHOU_BOARD3X3
	MOV AL, [DI]
	CMP AL, JOGADOR_CURR_CHAR
	JNE PROXIMA_LINHA3X3
	INC DI
	INC DX
	JMP VERIFICA_LINHA3X3
	
PROXIMA_LINHA3X3:
	XOR DX, DX
	LEA DI, BOARD_3X3
	INC CX
	ADD BX, 3
	ADD DI, BX
	JMP VERIFICA_LINHA3X3

VERIFICA_COLUNA3X3:
	XOR BX, BX
	XOR CX, CX
	XOR DX, DX
	LEA DI, BOARD_3X3
	
COLUNA_LOOP3X3:
	CMP CX, 3
	JE VERIFICA_DIAGONAL13X3
	CMP DX, 3
	JE GANHOU_BOARD3X3
	MOV AL, [DI]
	CMP AL, JOGADOR_CURR_CHAR
	JNE PROXIMA_COLUNA3X3
	ADD DI, 3
	INC DX
	JMP COLUNA_LOOP3X3

PROXIMA_COLUNA3X3:
	XOR DX, DX
	LEA DI, BOARD_3X3
	INC BX
	INC CX
	ADD DI, BX
	JMP COLUNA_LOOP3X3
	
VERIFICA_DIAGONAL13X3:
	XOR CX, CX
	LEA DI, BOARD_3X3

DIAGONAL1_LOOP3X3:
	CMP CX, 3
	JE GANHOU_BOARD3X3
	MOV AL, [DI]
	CMP AL, JOGADOR_CURR_CHAR
	JNE VERIFICA_DIAGONAL23X3
	ADD DI, 4
	INC CX
	JMP DIAGONAL1_LOOP3X3
	
VERIFICA_DIAGONAL23X3:
	XOR CX, CX
	LEA DI, BOARD_3X3
	ADD DI, 2
	
DIAGONAL2_LOOP3X3:
	CMP CX, 3
	JE GANHOU_BOARD3X3
	MOV AL, [DI]
	CMP AL, JOGADOR_CURR_CHAR
	JNE NAO_GANHOU_BOARD3X3
	ADD DI, 2
	INC CX
	JMP DIAGONAL2_LOOP3X3
	
NAO_GANHOU_BOARD3X3:
	MOV AL, 0
	RET
	
GANHOU_BOARD3X3:
	MOV AL, 1
	RET
VERIFICA_VENCEDOR_3X3 ENDP




